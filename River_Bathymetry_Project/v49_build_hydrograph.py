def _sample_line(dataset, line: LineString, spacing_m: float) -> np.ndarray:
    count = max(2, min(1200, int(math.ceil(line.length / max(spacing_m, 1.0))) + 1))
    distances = np.linspace(0.0, float(line.length), count)
    coords = [(line.interpolate(float(d)).x, line.interpolate(float(d)).y) for d in distances]
    values = np.array([v[0] for v in dataset.sample(coords)], dtype=float)
    if dataset.nodata is not None:
        values = values[values != float(dataset.nodata)]
    return values[np.isfinite(values)]


def add_reach_evidence(
    reaches: list[dict],
    inventory: gpd.GeoDataFrame,
    dem_ds,
    jrc_ds,
    osm_ds,
    config: HydrographConfig,
) -> list[dict]:
    linear_classes = {"RIVER_CANDIDATE", "OSM_WATERWAY_CANDIDATE", "ESTUARY_REVIEW_REQUIRED"}
    output = []
    spatial_index = inventory.sindex
    for rec in reaches:
        item = dict(rec)
        line: LineString = item["geometry"]
        query_geom = line.buffer(config.evidence_buffer_m)
        hit_indexes = list(spatial_index.query(query_geom, predicate="intersects"))
        hits = inventory.iloc[hit_indexes] if hit_indexes else inventory.iloc[0:0]
        hit_ids = sorted(str(v) for v in hits.get("object_id", pd.Series(dtype=str)).tolist())
        hit_classes = sorted(str(v) for v in hits.get("provisional_class", pd.Series(dtype=str)).unique().tolist())

        dem_values = _sample_line(dem_ds, line, max(line.length, 1.0))
        # Explicit endpoints are more useful than a two-point evenly-spaced sample
        # when diagnosing downstream rises.
        endpoint_values = np.array(
            [v[0] for v in dem_ds.sample([line.coords[0], line.coords[-1]])], dtype=float
        )
        dem_start = float(endpoint_values[0])
        dem_end = float(endpoint_values[1])
        jrc_values = _sample_line(jrc_ds, line, config.sample_spacing_m)
        jrc_values = jrc_values[(jrc_values >= 0) & (jrc_values <= 100)]
        osm_values = _sample_line(osm_ds, line, config.sample_spacing_m)

        item["length_m"] = float(line.length)
        item["water_object_ids"] = "|".join(hit_ids)
        item["water_object_classes"] = "|".join(hit_classes)
        item["water_object_count"] = int(len(hit_ids))
        item["linear_water_object_support"] = bool(any(c in linear_classes for c in hit_classes))
        item["jrc_occurrence_median"] = float(np.median(jrc_values)) if jrc_values.size else np.nan
        item["jrc_occurrence_ge20_fraction"] = float(np.mean(jrc_values >= 20.0)) if jrc_values.size else 0.0
        item["osm_distance_min_m"] = float(np.min(osm_values)) if osm_values.size else np.nan
        item["osm_within90_fraction"] = float(np.mean(osm_values <= 90.0)) if osm_values.size else 0.0
        item["dem_start_m"] = dem_start
        item["dem_end_m"] = dem_end
        item["dem_downstream_rise_m"] = dem_end - dem_start
        item["dem_downhill_qa_flag"] = bool(dem_end > dem_start + config.dem_downhill_qa_tolerance_m)
        item["major_reach"] = bool(
            int(_safe_number(item.get("ORD_STRA"), 0)) >= config.major_strahler_min
            or float(_safe_number(item.get("UPLAND_SKM"), 0.0)) >= config.major_upland_skm_min
        )
        item["review_required"] = bool(
            item.get("topology_review_required", False)
            or item.get("source_type") == "LEGACY_CANAL_CANDIDATE"
            or "OPEN_WATER_REVIEW_REQUIRED" in hit_classes
            or "ESTUARY_REVIEW_REQUIRED" in hit_classes
        )
        output.append(item)
    return output


def _jsonable(value):
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating,)):
        return None if not np.isfinite(value) else float(value)
    if isinstance(value, np.bool_):
        return bool(value)
    if isinstance(value, Path):
        return str(value)
    return value


def build_graph_audit(
    reaches_gdf: gpd.GeoDataFrame,
    nodes_gdf: gpd.GeoDataFrame,
    structures_gdf: gpd.GeoDataFrame,
    inventory: gpd.GeoDataFrame,
    issues: list[dict],
    osm_vector_candidates: Sequence[Path],
) -> dict:
    graph = nx.DiGraph()
    for _, row in reaches_gdf.iterrows():
        graph.add_edge(str(row.from_node), str(row.to_node), reach_id=str(row.reach_id))
    cycles = list(nx.simple_cycles(graph))

    node_types = nodes_gdf.set_index("node_id")["node_type"].to_dict()
    hydro = reaches_gdf[reaches_gdf.source_type == "HYDRORIVERS"].copy()
    major = hydro[hydro.major_reach]
    orphan_major = major[
        major.from_node.map(node_types).eq("HEADWATER")
        & (pd.to_numeric(major.ORD_STRA, errors="coerce").fillna(0) >= 4)
    ]
    unresolved = reaches_gdf[reaches_gdf.terminal_type == "UNRESOLVED_REVIEW"]
    # Only audit geometry gaps for edges that the graph actually connects.
    # A HydroRIVERS NEXT_DOWN relation may leave the model domain and later
    # re-enter; those reaches are intentionally represented as DOMAIN_EXIT /
    # DOMAIN_ENTRY rather than a false in-domain edge.
    endpoint_gaps = reaches_gdf[
        reaches_gdf.next_reach_id.fillna("").astype(str).ne("")
        & (
            pd.to_numeric(reaches_gdf.downstream_geometry_gap_m, errors="coerce").fillna(0)
            > 120.0
        )
    ]

    linear_classes = {"RIVER_CANDIDATE", "OSM_WATERWAY_CANDIDATE", "ESTUARY_REVIEW_REQUIRED"}
    linear_inventory = inventory[inventory.provisional_class.isin(linear_classes)].copy()
    covered_objects: set[str] = set()
    for raw in reaches_gdf.water_object_ids.fillna("").astype(str):
        covered_objects.update(v for v in raw.split("|") if v)
    missing_linear = linear_inventory[~linear_inventory.object_id.astype(str).isin(covered_objects)]

    confluence_nodes = nodes_gdf[nodes_gdf.node_type == "CONFLUENCE"]
    structure_ids = set(structures_gdf.structure_id.astype(str))
    osm_vector_status = [
        {"path": str(path), "exists": path.exists(), "size_bytes": path.stat().st_size if path.exists() else None}
        for path in osm_vector_candidates
    ]
    usable_osm_vector = any(item["exists"] and item["size_bytes"] and item["size_bytes"] > 0 for item in osm_vector_status)

    topology_pass = (
        len(orphan_major) == 0
        and len(cycles) == 0
        and len(unresolved) == 0
        and len(endpoint_gaps) == 0
        and "STRUCT_DONG_CAM" in structure_ids
    )

    # Gate B is intentionally a graph-topology gate. Bed-elevation ordering is
    # a later hydraulic-geometry requirement because V49-B has no defensible
    # bed elevation yet. Copernicus DEM values over water are QA evidence only,
    # not bathymetry.
    bed_gate_status = "DEFERRED_TO_V49_D_E_BY_DESIGN"
    gate_b_pass = bool(topology_pass)

    return {
        "schema_version": "V49-B-1",
        "reach_count": int(len(reaches_gdf)),
        "hydrorivers_reach_count": int((reaches_gdf.source_type == "HYDRORIVERS").sum()),
        "legacy_canal_candidate_count": int((reaches_gdf.source_type == "LEGACY_CANAL_CANDIDATE").sum()),
        "node_count": int(len(nodes_gdf)),
        "structure_count": int(len(structures_gdf)),
        "confluence_count": int(len(confluence_nodes)),
        "terminal_type_counts": {
            str(k): int(v)
            for k, v in reaches_gdf.loc[reaches_gdf.terminal_type.astype(str) != "", "terminal_type"].value_counts().to_dict().items()
        },
        "major_reach_count": int(reaches_gdf.major_reach.sum()),
        "orphan_major_reach_count": int(len(orphan_major)),
        "orphan_major_reach_ids": orphan_major.reach_id.astype(str).tolist(),
        "directed_cycle_count": int(len(cycles)),
        "directed_cycles": [[str(v) for v in cycle] for cycle in cycles[:25]],
        "unresolved_terminal_count": int(len(unresolved)),
        "unresolved_terminal_reach_ids": unresolved.reach_id.astype(str).tolist(),
        "endpoint_gap_over_120m_count": int(len(endpoint_gaps)),
        "endpoint_gap_reach_ids": endpoint_gaps.reach_id.astype(str).tolist(),
        "linear_water_object_count": int(len(linear_inventory)),
        "linear_water_object_without_graph_support_count": int(len(missing_linear)),
        "linear_water_object_without_graph_support_ids": missing_linear.object_id.astype(str).tolist(),
        "dem_downhill_qa_flag_count": int(reaches_gdf.dem_downhill_qa_flag.sum()),
        "review_required_reach_count": int(reaches_gdf.review_required.sum()),
        "issue_count": int(len(issues)),
        "issue_type_counts": dict(pd.Series([i["issue_type"] for i in issues], dtype=str).value_counts()),
        "dong_cam_explicit": bool("STRUCT_DONG_CAM" in structure_ids),
        "osm_vector_files": osm_vector_status,
        "usable_osm_vector_available": bool(usable_osm_vector),
        "topology_gate_pass": bool(topology_pass),
        "bed_elevation_ordering_gate": bed_gate_status,
        "gate_b_pass": bool(gate_b_pass),
        "gate_b_reason": (
            "Gate B certifies directed hydrographic topology only: no orphan major reaches, no unexplained directed cycles, "
            "all reaches have a downstream target or explicit terminal type, confluences are represented as explicit junction nodes, "
            "and known structures are explicit. Physical bed-elevation ordering is deferred by design to V49-D/E."
        ),
    }


def _prepare_gpkg_frame(frame: gpd.GeoDataFrame) -> gpd.GeoDataFrame:
    out = frame.copy()
    for column in out.columns:
        if column == "geometry":
            continue
        if out[column].dtype == bool:
            out[column] = out[column].astype(np.int8)
    return out


def write_map(
    reaches: gpd.GeoDataFrame,
    structures: gpd.GeoDataFrame,
    inventory: gpd.GeoDataFrame,
    output_path: Path,
) -> None:
    fig, ax = plt.subplots(figsize=(12, 12))
    ocean = inventory[inventory.provisional_class == "OCEAN"]
    inland = inventory[inventory.provisional_class != "OCEAN"]
    if not ocean.empty:
        ocean.plot(ax=ax, alpha=0.18, edgecolor="none")
    if not inland.empty:
        inland.boundary.plot(ax=ax, linewidth=0.35, alpha=0.45)
    hydro = reaches[reaches.source_type == "HYDRORIVERS"]
    canals = reaches[reaches.source_type == "LEGACY_CANAL_CANDIDATE"]
    if not hydro.empty:
        hydro.plot(ax=ax, linewidth=np.where(hydro.major_reach, 1.3, 0.55), alpha=0.85)
    if not canals.empty:
        canals.plot(ax=ax, linewidth=1.1, linestyle="--", alpha=0.9)
    if not structures.empty:
        structures.plot(ax=ax, markersize=70, marker="D")
    ax.set_title("V49-B Directed Hydrographic Graph — Phu Yen BG_Flood Domain")
    ax.set_xlabel("UTM Easting (m), EPSG:32649")
    ax.set_ylabel("UTM Northing (m)")
    ax.set_aspect("equal")
    fig.tight_layout()
    fig.savefig(output_path, dpi=180)
    plt.close(fig)


def build_hydrograph(
    dem_path: Path = DEFAULT_DEM,
    hydro_path: Path = DEFAULT_HYDRO,
    jrc_path: Path = DEFAULT_JRC,
    osm_distance_path: Path = DEFAULT_OSM_DISTANCE,
    inventory_path: Path = DEFAULT_INVENTORY,
    network_npz_path: Path = DEFAULT_NETWORK,
    output_dir: Path = DEFAULT_OUTPUT_DIR,
    config: HydrographConfig = HydrographConfig(),
) -> dict:
    output_dir.mkdir(parents=True, exist_ok=True)
    dem_hash_before = sha256_file(dem_path)

    with rasterio.open(dem_path) as dem_ds:
        model_crs = dem_ds.crs
        domain_polygon = box(*dem_ds.bounds)
        transform = dem_ds.transform
        dong_cam_xy = raster_xy(transform, config.dong_cam_row, config.dong_cam_col, offset="center")
        dong_cam_landmark = Point(dong_cam_xy)

    buffered = read_hydrorivers_buffered(hydro_path, model_crs, domain_polygon, config.source_buffer_m)
    oriented = normalize_hydrorivers_direction(buffered)
    clipped_records, clip_issues = clip_domain_reaches(oriented, domain_polygon)

    inventory = gpd.read_file(inventory_path, layer="water_objects").to_crs(model_crs)
    ocean_rows = inventory[inventory.provisional_class == "OCEAN"]
    ocean_geometry = ocean_rows.geometry.union_all() if not ocean_rows.empty else None
    inland_rows = inventory[inventory.provisional_class != "OCEAN"]
    persistent_water_geometry = inland_rows.geometry.union_all() if not inland_rows.empty else None

    split_records, structure, structure_issues = split_at_dong_cam(
        clipped_records, dong_cam_landmark, config.dong_cam_max_snap_m
    )
    assigned = assign_reach_ids(split_records)
    topo_reaches, node_records, topology_issues = build_topology(
        assigned,
        structure,
        buffered,
        domain_polygon,
        ocean_geometry,
        persistent_water_geometry,
        config,
    )

    canals = legacy_canal_records(network_npz_path, transform, model_crs)
    all_reaches = topo_reaches + canals
    node_records = add_legacy_canal_nodes(node_records, canals)

    with rasterio.open(dem_path) as dem_ds, rasterio.open(jrc_path) as jrc_ds, rasterio.open(
        osm_distance_path
    ) as osm_ds:
        if dem_ds.shape != jrc_ds.shape or dem_ds.shape != osm_ds.shape:
            raise ValueError("V49-B evidence rasters do not share the DEM grid")
        all_reaches = add_reach_evidence(all_reaches, inventory, dem_ds, jrc_ds, osm_ds, config)

    reaches_gdf = gpd.GeoDataFrame(all_reaches, geometry="geometry", crs=model_crs)
    # Remove build-only columns that GeoPackage cannot serialize usefully.
    drop_cols = ["forced_reach_id", "to_structure", "from_structure"]
    reaches_gdf = reaches_gdf.drop(columns=[c for c in drop_cols if c in reaches_gdf.columns])
    nodes_gdf = gpd.GeoDataFrame(node_records, geometry="geometry", crs=model_crs)
    structures_gdf = gpd.GeoDataFrame([structure], geometry="geometry", crs=model_crs)

    issues = clip_issues + structure_issues + topology_issues
    for rec in canals:
        issues.append(
            {
                "issue_type": "LEGACY_CANAL_CANDIDATE",
                "severity": "REVIEW",
                "hyriv_id": -1,
                "reach_id": rec["reach_id"],
                "message": "Canal retained as a graph candidate; requires independent vector/engineering verification before hydraulic geometry is assigned.",
                "geometry": Point(rec["geometry"].coords[0]),
            }
        )
    issues_gdf = gpd.GeoDataFrame(issues, geometry="geometry", crs=model_crs)

    audit = build_graph_audit(
        reaches_gdf,
        nodes_gdf,
        structures_gdf,
        inventory,
        issues,
        DEFAULT_OSM_VECTOR_CANDIDATES,
    )
    audit.update(
        {
            "dem_path": str(dem_path),
            "dem_sha256_before": dem_hash_before,
            "dem_sha256_after": sha256_file(dem_path),
            "hydrorivers_path": str(hydro_path),
            "hydrorivers_buffered_feature_count": int(len(buffered)),
            "hydrorivers_in_domain_native_feature_count": int(reaches_gdf.loc[reaches_gdf.source_type == "HYDRORIVERS", "HYRIV_ID"].nunique()),
            "inventory_path": str(inventory_path),
            "network_npz_path": str(network_npz_path),
            "config": asdict(config),
        }
    )
    audit["dem_unchanged"] = audit["dem_sha256_before"] == audit["dem_sha256_after"]

    gpkg = output_dir / "V49_hydrograph.gpkg"
    if gpkg.exists():
        gpkg.unlink()
    _prepare_gpkg_frame(reaches_gdf).to_file(gpkg, layer="reaches", driver="GPKG")
    _prepare_gpkg_frame(nodes_gdf).to_file(gpkg, layer="nodes", driver="GPKG")
    _prepare_gpkg_frame(structures_gdf).to_file(gpkg, layer="structures", driver="GPKG")
    if not issues_gdf.empty:
        _prepare_gpkg_frame(issues_gdf).to_file(gpkg, layer="issues", driver="GPKG")

    reaches_gdf.drop(columns="geometry").to_csv(output_dir / "V49_reach_table.csv", index=False)
    nodes_gdf.drop(columns="geometry").to_csv(output_dir / "V49_node_table.csv", index=False)
    with (output_dir / "V49_graph_audit.json").open("w", encoding="utf-8") as stream:
        json.dump(audit, stream, ensure_ascii=False, indent=2, default=_jsonable)
    write_map(reaches_gdf, structures_gdf, inventory, output_dir / "V49_hydrograph_map.png")

    return audit


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dem", type=Path, default=DEFAULT_DEM)
    parser.add_argument("--hydrorivers", type=Path, default=DEFAULT_HYDRO)
    parser.add_argument("--jrc", type=Path, default=DEFAULT_JRC)
    parser.add_argument("--osm-distance", type=Path, default=DEFAULT_OSM_DISTANCE)
    parser.add_argument("--inventory", type=Path, default=DEFAULT_INVENTORY)
    parser.add_argument("--network-npz", type=Path, default=DEFAULT_NETWORK)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    args = parser.parse_args()
    audit = build_hydrograph(
        dem_path=args.dem,
        hydro_path=args.hydrorivers,
        jrc_path=args.jrc,
        osm_distance_path=args.osm_distance,
        inventory_path=args.inventory,
        network_npz_path=args.network_npz,
        output_dir=args.output_dir,
    )
    print(json.dumps(audit, ensure_ascii=False, indent=2, default=_jsonable))


if __name__ == "__main__":
    main()
