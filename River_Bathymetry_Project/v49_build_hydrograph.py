def sha256_file(path: Path, chunk_size: int = 1024 * 1024) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        while True:
            chunk = stream.read(chunk_size)
            if not chunk:
                return digest.hexdigest()
            digest.update(chunk)


def _safe_number(value, default=0.0):
    if value is None or (isinstance(value, float) and not math.isfinite(value)):
        return default
    try:
        if pd.isna(value):
            return default
    except TypeError:
        pass
    return value


def _single_line(geometry) -> LineString:
    """Return one usable line for a HydroRIVERS feature."""

    if isinstance(geometry, LineString):
        return geometry
    if isinstance(geometry, MultiLineString):
        merged = linemerge(geometry)
        if isinstance(merged, LineString):
            return merged
        if isinstance(merged, MultiLineString):
            return max(merged.geoms, key=lambda g: g.length)
    raise ValueError(f"Unsupported HydroRIVERS geometry type: {geometry.geom_type}")


def _line_parts(geometry) -> list[LineString]:
    if geometry is None or geometry.is_empty:
        return []
    if isinstance(geometry, LineString):
        return [geometry] if geometry.length > 0 else []
    if isinstance(geometry, MultiLineString):
        return [g for g in geometry.geoms if g.length > 0]
    if isinstance(geometry, GeometryCollection):
        out: list[LineString] = []
        for item in geometry.geoms:
            out.extend(_line_parts(item))
        return out
    return []


def reverse_line(line: LineString) -> LineString:
    return LineString(list(line.coords)[::-1])


def orient_reach_geometry(
    geometry: LineString,
    downstream_geometry: LineString | None,
    predecessor_geometries: Sequence[LineString],
) -> tuple[LineString, bool, str, float, float]:
    """Orient one reach upstream->downstream using graph-neighbour evidence.

    The two candidate orientations are scored against the NEXT_DOWN geometry
    and any predecessor geometries.  DEM elevation is intentionally absent.
    """

    line = _single_line(geometry)
    start = Point(line.coords[0])
    end = Point(line.coords[-1])

    def down_cost(point: Point) -> float:
        if downstream_geometry is None:
            return 0.0
        return float(point.distance(downstream_geometry))

    def up_cost(point: Point) -> float:
        if not predecessor_geometries:
            return 0.0
        return float(min(point.distance(g) for g in predecessor_geometries))

    native_score = down_cost(end) + up_cost(start)
    reversed_score = down_cost(start) + up_cost(end)
    evidence_terms = int(downstream_geometry is not None) + int(bool(predecessor_geometries))

    if evidence_terms == 0:
        return line, False, "NATIVE_FALLBACK_NO_NEIGHBOUR", native_score, reversed_score
    if reversed_score + 1.0e-6 < native_score:
        return reverse_line(line), True, "GRAPH_NEIGHBOUR", native_score, reversed_score
    return line, False, "GRAPH_NEIGHBOUR", native_score, reversed_score


def read_hydrorivers_buffered(
    path: Path,
    model_crs,
    domain_polygon,
    buffer_m: float,
) -> gpd.GeoDataFrame:
    search_polygon = domain_polygon.buffer(float(buffer_m))
    transformer = Transformer.from_crs(model_crs, "EPSG:4326", always_xy=True)
    minx, miny, maxx, maxy = search_polygon.bounds
    corners = [
        transformer.transform(minx, miny),
        transformer.transform(minx, maxy),
        transformer.transform(maxx, miny),
        transformer.transform(maxx, maxy),
    ]
    bbox4326 = (
        min(x for x, _ in corners),
        min(y for _, y in corners),
        max(x for x, _ in corners),
        max(y for _, y in corners),
    )
    frame = gpd.read_file(path, bbox=bbox4326).to_crs(model_crs)
    frame = frame[frame.geometry.intersects(search_polygon)].copy()
    frame["HYRIV_ID"] = pd.to_numeric(frame["HYRIV_ID"], errors="raise").astype(np.int64)
    frame["NEXT_DOWN"] = pd.to_numeric(frame["NEXT_DOWN"], errors="coerce").fillna(0).astype(np.int64)
    return frame.reset_index(drop=True)


def normalize_hydrorivers_direction(frame: gpd.GeoDataFrame) -> gpd.GeoDataFrame:
    by_id = {int(row.HYRIV_ID): _single_line(row.geometry) for _, row in frame.iterrows()}
    predecessors: dict[int, list[int]] = defaultdict(list)
    for _, row in frame.iterrows():
        target = int(row.NEXT_DOWN)
        if target in by_id:
            predecessors[target].append(int(row.HYRIV_ID))

    records = []
    for _, row in frame.iterrows():
        rid = int(row.HYRIV_ID)
        target = int(row.NEXT_DOWN)
        downstream = by_id.get(target)
        upstream = [by_id[p] for p in predecessors.get(rid, [])]
        oriented, was_reversed, method, score_native, score_reversed = orient_reach_geometry(
            by_id[rid], downstream, upstream
        )
        rec = row.to_dict()
        rec["geometry"] = oriented
        rec["geometry_reversed"] = bool(was_reversed)
        rec["orientation_method"] = method
        rec["orientation_native_score_m"] = float(score_native)
        rec["orientation_reversed_score_m"] = float(score_reversed)
        records.append(rec)
    return gpd.GeoDataFrame(records, geometry="geometry", crs=frame.crs)


def _project_order(reference: LineString, part: LineString) -> float:
    midpoint = part.interpolate(0.5, normalized=True)
    return float(reference.project(midpoint))


def clip_domain_reaches(oriented: gpd.GeoDataFrame, domain_polygon) -> tuple[list[dict], list[dict]]:
    records: list[dict] = []
    issues: list[dict] = []
    for _, row in oriented.iterrows():
        native = _single_line(row.geometry)
        clipped = native.intersection(domain_polygon)
        parts = _line_parts(clipped)
        if not parts:
            continue
        parts.sort(key=lambda g: _project_order(native, g))
        if len(parts) > 1:
            issues.append(
                {
                    "issue_type": "MULTIPART_DOMAIN_CLIP",
                    "severity": "REVIEW",
                    "hyriv_id": int(row.HYRIV_ID),
                    "message": f"HydroRIVERS reach re-enters the model domain in {len(parts)} parts.",
                    "geometry": Point(parts[0].coords[-1]),
                }
            )
        for index, part in enumerate(parts, start=1):
            start_proj = native.project(Point(part.coords[0]))
            end_proj = native.project(Point(part.coords[-1]))
            if end_proj < start_proj:
                part = reverse_line(part)
            rec = row.drop(labels=["geometry"]).to_dict()
            rec.update(
                {
                    "native_part_index": index,
                    "native_part_count": len(parts),
                    "geometry": part,
                }
            )
            records.append(rec)
    return records, issues


def split_at_dong_cam(
    records: list[dict],
    landmark: Point,
    max_snap_m: float,
) -> tuple[list[dict], dict, list[dict]]:
    """Split the nearest HydroRIVERS reach and create one structure record."""

    if not records:
        raise ValueError("No in-domain HydroRIVERS reaches are available for Dong Cam snapping")

    distances = [(float(rec["geometry"].distance(landmark)), i) for i, rec in enumerate(records)]
    snap_distance, selected_index = min(distances)
    selected = records[selected_index]
    if snap_distance > max_snap_m:
        raise ValueError(
            f"Dong Cam landmark is {snap_distance:.1f} m from the nearest HydroRIVERS reach; "
            f"limit is {max_snap_m:.1f} m"
        )
    line: LineString = selected["geometry"]
    chainage = float(line.project(landmark))
    if chainage <= 1.0 or chainage >= line.length - 1.0:
        raise ValueError("Dong Cam snap lands too close to a reach endpoint to create a stable split")
    snapped = line.interpolate(chainage)
    upstream = substring(line, 0.0, chainage)
    downstream = substring(line, chainage, line.length)
    if not isinstance(upstream, LineString) or not isinstance(downstream, LineString):
        raise ValueError("Dong Cam split did not produce two line segments")

    base_key = f"HR_{int(selected['HYRIV_ID'])}"
    if int(selected["native_part_count"]) > 1:
        base_key += f"_P{int(selected['native_part_index']):02d}"

    up_rec = dict(selected)
    up_rec.update(
        {
            "geometry": upstream,
            "forced_reach_id": base_key + "_U",
            "split_role": "UPSTREAM_OF_DONG_CAM",
            "to_structure": True,
            "from_structure": False,
        }
    )
    dn_rec = dict(selected)
    dn_rec.update(
        {
            "geometry": downstream,
            "forced_reach_id": base_key + "_D",
            "split_role": "DOWNSTREAM_OF_DONG_CAM",
            "to_structure": False,
            "from_structure": True,
        }
    )

    out = records[:selected_index] + [up_rec, dn_rec] + records[selected_index + 1 :]
    structure = {
        "structure_id": "STRUCT_DONG_CAM",
        "name": "Dong Cam Weir",
        "structure_type": "WEIR",
        "hyriv_id": int(selected["HYRIV_ID"]),
        "landmark_x": float(landmark.x),
        "landmark_y": float(landmark.y),
        "snap_distance_m": float(snap_distance),
        "source": "V48 verified 187-cell protected mask; snapped to HydroRIVERS for V49-B topology",
        "review_required": False,
        "geometry": snapped,
    }
    issue = {
        "issue_type": "STRUCTURE_SNAP",
        "severity": "INFO",
        "hyriv_id": int(selected["HYRIV_ID"]),
        "message": f"Dong Cam landmark snapped {snap_distance:.2f} m to HydroRIVERS and split the reach.",
        "geometry": snapped,
    }
    return out, structure, [issue]


def assign_reach_ids(records: list[dict]) -> list[dict]:
    counts = defaultdict(int)
    for rec in records:
        counts[int(rec["HYRIV_ID"])] += 1
    seen = defaultdict(int)
    out = []
    for rec in records:
        item = dict(rec)
        if item.get("forced_reach_id"):
            item["reach_id"] = str(item["forced_reach_id"])
        else:
            native_id = int(item["HYRIV_ID"])
            seen[native_id] += 1
            if counts[native_id] == 1:
                item["reach_id"] = f"HR_{native_id}"
            else:
                item["reach_id"] = f"HR_{native_id}_P{seen[native_id]:02d}"
        item.setdefault("split_role", "NONE")
        item.setdefault("to_structure", False)
        item.setdefault("from_structure", False)
        out.append(item)
    return out


def _inside_native_map(records: list[dict]) -> dict[int, list[dict]]:
    mapping: dict[int, list[dict]] = defaultdict(list)
    for rec in records:
        mapping[int(rec["HYRIV_ID"])].append(rec)
    # Existing list order follows oriented native reach and structure split.
    return mapping


def _point_near_boundary(point: Point, domain_polygon, tolerance: float) -> bool:
    return float(point.distance(domain_polygon.boundary)) <= tolerance


def _terminal_type(
    rec: Mapping,
    endpoint: Point,
    domain_polygon,
    ocean_geometry,
    persistent_water_geometry,
    in_domain_native_ids: set[int],
    config: HydrographConfig,
) -> tuple[str, str]:
    endorheic = int(_safe_number(rec.get("ENDORHEIC"), 0)) == 1
    next_down = int(_safe_number(rec.get("NEXT_DOWN"), 0))
    if endorheic:
        return "ENDORHEIC", "HydroRIVERS marks the reach as endorheic."
    if ocean_geometry is not None and not ocean_geometry.is_empty:
        ocean_distance = float(endpoint.distance(ocean_geometry))
        if ocean_distance <= config.ocean_outlet_tolerance_m:
            return "OCEAN_OUTLET", f"Reach endpoint is {ocean_distance:.1f} m from V49-A ocean water."
    if next_down == 0 and persistent_water_geometry is not None and not persistent_water_geometry.is_empty:
        water_distance = float(endpoint.distance(persistent_water_geometry))
        if water_distance <= config.evidence_buffer_m:
            return (
                "WATERBODY_TERMINAL_REVIEW",
                f"HydroRIVERS NEXT_DOWN=0 endpoint lies {water_distance:.1f} m from a V49-A persistent inland-water object; V49-C must classify the receiving water body.",
            )
    if _point_near_boundary(endpoint, domain_polygon, config.terminal_boundary_tolerance_m):
        return "DOMAIN_EXIT", "Directed reach terminates on the model boundary."
    if next_down and next_down not in in_domain_native_ids:
        return "DOMAIN_EXIT", "NEXT_DOWN continues outside the model-domain reach set."
    if next_down == 0:
        return "UNRESOLVED_REVIEW", "HydroRIVERS terminal is inland and not endorheic/ocean-adjacent."
    return "UNRESOLVED_REVIEW", "NEXT_DOWN cannot be resolved to an in-domain reach or boundary outlet."


def build_topology(
    records: list[dict],
    structure: dict,
    buffered_hydro: gpd.GeoDataFrame,
    domain_polygon,
    ocean_geometry,
    persistent_water_geometry,
    config: HydrographConfig,
) -> tuple[list[dict], list[dict], list[dict]]:
    native_map = _inside_native_map(records)
    in_domain_ids = set(native_map)
    buffered_ids = set(int(v) for v in buffered_hydro.HYRIV_ID.tolist())

    # Each native feature contributes one logical in-domain chain unless it was
    # split by the structure.  Re-entry multipart clips are kept as review
    # pieces; each disconnected piece receives its own boundary terminal.
    first_record = {native_id: items[0] for native_id, items in native_map.items()}
    first_node_id = {native_id: f"N_HR_{native_id}_UP" for native_id in native_map}

    predecessor_ids: dict[int, list[int]] = defaultdict(list)
    for native_id, items in native_map.items():
        target = int(_safe_number(items[-1].get("NEXT_DOWN"), 0))
        if target in in_domain_ids:
            predecessor_ids[target].append(native_id)

    nodes: dict[str, dict] = {}
    reaches_out: list[dict] = []
    issues: list[dict] = []

    # Prepare upstream nodes.
    for native_id, items in native_map.items():
        start = Point(items[0]["geometry"].coords[0])
        preds = predecessor_ids.get(native_id, [])
        if len(preds) >= 2:
            node_type = "CONFLUENCE"
        elif len(preds) == 1:
            node_type = "JUNCTION"
        elif _point_near_boundary(start, domain_polygon, config.terminal_boundary_tolerance_m):
            node_type = "DOMAIN_ENTRY"
        else:
            node_type = "HEADWATER"
        node_id = first_node_id[native_id]
        nodes[node_id] = {
            "node_id": node_id,
            "node_type": node_type,
            "terminal_type": "",
            "hyriv_id": native_id,
            "incoming_count": len(preds),
            "outgoing_count": 1,
            "structure_id": "",
            "review_required": False,
            "geometry": start,
        }

    struct_node = dict(structure)
    nodes[structure["structure_id"]] = {
        "node_id": structure["structure_id"],
        "node_type": "STRUCTURE_WEIR",
        "terminal_type": "",
        "hyriv_id": int(structure["hyriv_id"]),
        "incoming_count": 1,
        "outgoing_count": 1,
        "structure_id": structure["structure_id"],
        "review_required": False,
        "geometry": structure["geometry"],
    }

    for native_id, items in native_map.items():
        # Multipart clips are disconnected by definition.  Structure splits are
        # continuous and explicitly linked through STRUCT_DONG_CAM.
        previous_to_node = first_node_id[native_id]
        for index, rec in enumerate(items):
            item = dict(rec)
            geom: LineString = item["geometry"]
            item["source_type"] = "HYDRORIVERS"
            item["from_node"] = structure["structure_id"] if item.get("from_structure") else previous_to_node
            item["terminal_type"] = ""
            item["terminal_reason"] = ""
            item["topology_review_required"] = False
            item["next_reach_id"] = ""

            if item.get("to_structure"):
                item["to_node"] = structure["structure_id"]
                # Next list item is the downstream half of the same native reach.
                if index + 1 < len(items):
                    item["next_reach_id"] = str(items[index + 1]["reach_id"])
                previous_to_node = structure["structure_id"]
            elif index + 1 < len(items):
                # If the same native reach has multiple domain-clip pieces,
                # there is an outside-domain gap.  Do not bridge it silently.
                if int(item.get("native_part_count", 1)) > 1 and not items[index + 1].get("from_structure"):
                    terminal_id = f"T_{item['reach_id']}"
                    item["to_node"] = terminal_id
                    item["terminal_type"] = "DOMAIN_EXIT"
                    item["terminal_reason"] = "Native HydroRIVERS reach leaves the domain before a later re-entry piece."
                    nodes[terminal_id] = {
                        "node_id": terminal_id,
                        "node_type": "TERMINAL",
                        "terminal_type": "DOMAIN_EXIT",
                        "hyriv_id": native_id,
                        "incoming_count": 1,
                        "outgoing_count": 0,
                        "structure_id": "",
                        "review_required": False,
                        "geometry": Point(geom.coords[-1]),
                    }
                    # Later piece needs an explicit domain-entry node.
                    reentry_id = f"N_{items[index + 1]['reach_id']}_ENTRY"
                    nodes[reentry_id] = {
                        "node_id": reentry_id,
                        "node_type": "DOMAIN_ENTRY",
                        "terminal_type": "",
                        "hyriv_id": native_id,
                        "incoming_count": 0,
                        "outgoing_count": 1,
                        "structure_id": "",
                        "review_required": True,
                        "geometry": Point(items[index + 1]["geometry"].coords[0]),
                    }
                    previous_to_node = reentry_id
                    issues.append(
                        {
                            "issue_type": "DOMAIN_REENTRY",
                            "severity": "REVIEW",
                            "hyriv_id": native_id,
                            "reach_id": item["reach_id"],
                            "message": "Reach exits and later re-enters model domain; pieces are not connected across the outside-domain gap.",
                            "geometry": Point(geom.coords[-1]),
                        }
                    )
                else:
                    next_item = items[index + 1]
                    if next_item.get("from_structure"):
                        next_node = structure["structure_id"]
                    else:
                        next_node = f"N_{next_item['reach_id']}_INTERNAL"
                        if next_node not in nodes:
                            nodes[next_node] = {
                                "node_id": next_node,
                                "node_type": "INTERNAL_SPLIT",
                                "terminal_type": "",
                                "hyriv_id": native_id,
                                "incoming_count": 1,
                                "outgoing_count": 1,
                                "structure_id": "",
                                "review_required": False,
                                "geometry": Point(next_item["geometry"].coords[0]),
                            }
                    item["to_node"] = next_node
                    item["next_reach_id"] = str(next_item["reach_id"])
                    previous_to_node = next_node
            else:
                next_down = int(_safe_number(item.get("NEXT_DOWN"), 0))
                if next_down in in_domain_ids:
                    target = first_record[next_down]
                    target_node = first_node_id[next_down]
                    gap = float(Point(geom.coords[-1]).distance(Point(target["geometry"].coords[0])))
                    item["downstream_geometry_gap_m"] = gap
                    endpoint_is_boundary = _point_near_boundary(
                        Point(geom.coords[-1]), domain_polygon, config.terminal_boundary_tolerance_m
                    )
                    if gap > config.endpoint_snap_tolerance_m and endpoint_is_boundary:
                        terminal_id = f"T_{item['reach_id']}"
                        item["to_node"] = terminal_id
                        item["next_reach_id"] = ""
                        item["terminal_type"] = "DOMAIN_EXIT"
                        item["terminal_reason"] = (
                            f"Reach exits the model boundary; NEXT_DOWN reappears {gap:.1f} m away inside the domain."
                        )
                        item["topology_review_required"] = False
                        nodes[terminal_id] = {
                            "node_id": terminal_id,
                            "node_type": "TERMINAL",
                            "terminal_type": "DOMAIN_EXIT",
                            "hyriv_id": native_id,
                            "incoming_count": 1,
                            "outgoing_count": 0,
                            "structure_id": "",
                            "review_required": False,
                            "geometry": Point(geom.coords[-1]),
                        }
                        # The downstream native reach is a fresh domain entry,
                        # not a direct edge across unmodelled space.
                        nodes[target_node]["node_type"] = "DOMAIN_ENTRY"
                        nodes[target_node]["incoming_count"] = 0
                        nodes[target_node]["review_required"] = False
                    else:
                        item["to_node"] = target_node
                        item["next_reach_id"] = str(target["reach_id"])
                    if gap > config.endpoint_snap_tolerance_m and not endpoint_is_boundary:
                        item["topology_review_required"] = True
                        issues.append(
                            {
                                "issue_type": "ENDPOINT_GAP",
                                "severity": "REVIEW",
                                "hyriv_id": native_id,
                                "reach_id": item["reach_id"],
                                "message": f"NEXT_DOWN topology is valid but geometry endpoints are {gap:.1f} m apart.",
                                "geometry": Point(geom.coords[-1]),
                            }
                        )
                else:
                    terminal_id = f"T_{item['reach_id']}"
                    terminal_type, reason = _terminal_type(
                        item,
                        Point(geom.coords[-1]),
                        domain_polygon,
                        ocean_geometry,
                        persistent_water_geometry,
                        in_domain_ids,
                        config,
                    )
                    item["to_node"] = terminal_id
                    item["terminal_type"] = terminal_type
                    item["terminal_reason"] = reason
                    item["downstream_geometry_gap_m"] = np.nan
                    review = terminal_type in {"UNRESOLVED_REVIEW", "WATERBODY_TERMINAL_REVIEW"}
                    item["topology_review_required"] = review
                    nodes[terminal_id] = {
                        "node_id": terminal_id,
                        "node_type": "TERMINAL",
                        "terminal_type": terminal_type,
                        "hyriv_id": native_id,
                        "incoming_count": 1,
                        "outgoing_count": 0,
                        "structure_id": "",
                        "review_required": review,
                        "geometry": Point(geom.coords[-1]),
                    }
                    if terminal_type == "UNRESOLVED_REVIEW":
                        issues.append(
                            {
                                "issue_type": "UNRESOLVED_TERMINAL",
                                "severity": "BLOCKER",
                                "hyriv_id": native_id,
                                "reach_id": item["reach_id"],
                                "message": reason,
                                "geometry": Point(geom.coords[-1]),
                            }
                        )
                previous_to_node = item["to_node"]

            item["next_down_present_in_buffer"] = int(_safe_number(item.get("NEXT_DOWN"), 0)) in buffered_ids
            reaches_out.append(item)

    return reaches_out, list(nodes.values()), issues


